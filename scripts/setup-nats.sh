#!/usr/bin/env bash
# NATS setup for xagent: checksum-verified nats-server binary, an authenticated JetStream config
# and a random password shared with xagent via a 0600 file. Loopback and plain TCP by default.
# With --tls it also makes a private CA and a server certificate (ECDSA P-256) in the
# strict-X.509 form rustls requires, and the server listens with TLS.
# Never overwrites an existing config, password or key.
#
#   scripts/setup-nats.sh [--version v2.14.6] [--listen 127.0.0.1:4222]
#                         [--tls [--san DNS_OR_IP]...]
set -euo pipefail

VERSION="v2.14.6"
LISTEN="127.0.0.1:4222"
TLS=0
SANS=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version) VERSION="$2"; shift 2 ;;
    --listen) LISTEN="$2"; shift 2 ;;
    --tls) TLS=1; shift ;;
    --san) SANS+=("$2"); shift 2 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done

BIN="$HOME/.local/bin"
CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/xagent"
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/xagent/nats"
mkdir -p "$BIN" "$CONF_DIR" "$DATA_DIR"
chmod 700 "$CONF_DIR" "$DATA_DIR"

if ! command -v nats-server >/dev/null 2>&1; then
  arch="$(uname -m)"; case "$arch" in x86_64) arch=amd64 ;; aarch64|arm64) arch=arm64 ;; esac
  os="$(uname -s | tr '[:upper:]' '[:lower:]')"
  name="nats-server-${VERSION}-${os}-${arch}"
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
  base="https://github.com/nats-io/nats-server/releases/download/${VERSION}"
  echo "==> downloading $name"
  curl -fsSL -o "$tmp/$name.tar.gz" "$base/$name.tar.gz"
  curl -fsSL -o "$tmp/SHA256SUMS" "$base/SHA256SUMS"
  (cd "$tmp" && grep " $name.tar.gz\$" SHA256SUMS | sha256sum -c -)
  tar -xzf "$tmp/$name.tar.gz" -C "$tmp"
  install -m 0755 "$tmp/$name/nats-server" "$BIN/nats-server"
  echo "==> installed $BIN/nats-server"
else
  echo "==> using $(command -v nats-server) ($(nats-server --version))"
fi

PW_FILE="$CONF_DIR/nats.password"
if [[ ! -f "$PW_FILE" ]]; then
  umask 177
  head -c 32 /dev/urandom | base64 | tr -d '/+=\n' | head -c 40 > "$PW_FILE"
  umask 022
  echo "==> generated $PW_FILE"
fi

TLS_BLOCK=""
SCHEME="nats"
if [[ $TLS -eq 1 ]]; then
  command -v openssl >/dev/null || { echo "--tls needs openssl" >&2; exit 1; }
  PKI="$CONF_DIR/pki"
  mkdir -p "$PKI"; chmod 700 "$PKI"
  if [[ ! -f "$PKI/ca.pem" ]]; then
    umask 177
    openssl ecparam -name prime256v1 -genkey -noout -out "$PKI/ca-key.pem"
    umask 022
    # CA: pathlen 0, may only sign certificates and CRLs. rustls refuses a CA without keyUsage.
    openssl req -x509 -new -key "$PKI/ca-key.pem" -sha256 -days 3650 -subj "/CN=xagent CA" \
      -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
      -addext "keyUsage=critical,keyCertSign,cRLSign" \
      -addext "subjectKeyIdentifier=hash" -out "$PKI/ca.pem"
    echo "==> generated $PKI/ca.pem (clients get only this file; ca-key.pem stays on this host)"
  fi
  if [[ ! -f "$PKI/server.pem" ]]; then
    host="$(hostname -s)"
    san="DNS:localhost,IP:127.0.0.1,DNS:$host"
    for name in ${SANS[@]+"${SANS[@]}"}; do
      if [[ "$name" =~ ^[0-9.]+$ || "$name" == *:* ]]; then san+=",IP:$name"; else san+=",DNS:$name"; fi
    done
    umask 177
    openssl ecparam -name prime256v1 -genkey -noout -out "$PKI/server-key.pem"
    umask 022
    openssl req -new -key "$PKI/server-key.pem" -subj "/CN=$host" -out "$PKI/server.csr"
    cat > "$PKI/server.ext" <<EXT
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature
extendedKeyUsage=serverAuth
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer
subjectAltName=$san
EXT
    openssl x509 -req -in "$PKI/server.csr" -CA "$PKI/ca.pem" -CAkey "$PKI/ca-key.pem" \
      -CAcreateserial -days 825 -sha256 -extfile "$PKI/server.ext" -out "$PKI/server.pem"
    rm -f "$PKI/server.csr"
    openssl verify -x509_strict -CAfile "$PKI/ca.pem" "$PKI/server.pem" >/dev/null
    echo "==> generated $PKI/server.pem (825 days, SANs: $san)"
  fi
  SCHEME="tls"
  TLS_BLOCK="tls {
  cert_file: \"$PKI/server.pem\"
  key_file: \"$PKI/server-key.pem\"
}"
fi

NATS_CONF="$CONF_DIR/nats-server.conf"
if [[ ! -f "$NATS_CONF" ]]; then
  umask 177
  cat > "$NATS_CONF" <<EOF
# generated by xagent scripts/setup-nats.sh
listen: $LISTEN
server_name: xagent-nats
http: 127.0.0.1:8222
$TLS_BLOCK
jetstream {
  store_dir: "$DATA_DIR"
  max_file_store: 4GB
  max_memory_store: 256MB
}
authorization {
  users = [
    {
      user: xagent
      password: "$(cat "$PW_FILE")"
      permissions: {
        publish: ["xagent.v1.>", "\$JS.API.>", "\$JS.ACK.>", "\$KV.XAGENT_TOPICS.>", "\$KV.XAGENT_AGENTS.>", "\$KV.XAGENT_LEASES.>", "\$KV.XAGENT_SUBSCRIPTIONS.>", "_INBOX.>"]
        subscribe: ["xagent.v1.>", "_INBOX.>", "\$KV.XAGENT_TOPICS.>", "\$KV.XAGENT_AGENTS.>", "\$KV.XAGENT_LEASES.>", "\$KV.XAGENT_SUBSCRIPTIONS.>"]
      }
    }
  ]
}
EOF
  umask 022
  echo "==> wrote $NATS_CONF (listen $LISTEN, JetStream at $DATA_DIR)"
else
  echo "==> kept existing $NATS_CONF"
fi

cat <<EOF
Set in ~/.config/xagent/config.toml:
  [nats]
  servers = ["$SCHEME://$LISTEN"]
  user = "xagent"
  password_file = "$PW_FILE"
EOF
if [[ $TLS -eq 1 ]]; then
  echo '  tls_ca = "~/.config/xagent/pki/ca.pem"   # copy ca.pem to every other host'
fi
